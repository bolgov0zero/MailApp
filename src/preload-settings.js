const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('mailappSettings', {
  getAppInfo:       ()      => ipcRenderer.invoke('settings:getAppInfo'),
  getDrives:        ()      => ipcRenderer.invoke('settings:getDrives'),
  load:             ()                  => ipcRenderer.invoke('settings:load'),
  listAuthFiles:    (drive)             => ipcRenderer.invoke('settings:listAuthFiles', drive),
  loadAuthByLogin:  (drive, login)      => ipcRenderer.invoke('settings:loadAuthByLogin', { drive, login }),
  save:             (data)  => ipcRenderer.invoke('settings:save', data),
  checkUpdate:          ()  => ipcRenderer.invoke('settings:checkUpdate'),
  downloadAndInstall:   ()  => ipcRenderer.invoke('settings:downloadAndInstall'),
  onUpdateProgress: (cb)    => ipcRenderer.on('update:progress', (_, pct) => cb(pct)),
  openExternal:     (url)   => ipcRenderer.invoke('settings:openExternal', url),
  deleteProfile:    (drive, login) => ipcRenderer.invoke('settings:deleteProfile', { drive, login }),
  relogin:          ()      => ipcRenderer.invoke('settings:relogin'),
  minimize:         ()      => ipcRenderer.send('settings:minimize'),
  close:            ()      => ipcRenderer.send('settings:close'),
  onUpdateDownloaded: (cb)  => ipcRenderer.on('update:downloaded', cb),
  serverStatus:     ()        => ipcRenderer.invoke('settings:serverStatus'),
  serverConnect:    (code)    => ipcRenderer.invoke('settings:serverConnect', code),
  serverDisconnect: ()        => ipcRenderer.invoke('settings:serverDisconnect'),
  getDiagnostics:   ()        => ipcRenderer.invoke('settings:getDiagnostics'),
  setLogging:       (enabled) => ipcRenderer.invoke('settings:setLogging', enabled),
  openLogsFolder:   ()        => ipcRenderer.invoke('settings:openLogsFolder'),
});
